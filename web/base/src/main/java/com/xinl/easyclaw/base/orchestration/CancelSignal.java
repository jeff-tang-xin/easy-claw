package com.xinl.easyclaw.base.orchestration;

/**
 * 取消信号 —— 编排层感知「用户已点停止」的唯一通道。
 * <p>
 * <b>为什么异步化后必须有它</b>：同步执行时，一步跑完才返回，中止只需在步骤边界
 * 判断一次；异步串联后，编排链可能已经排好了后续若干步，用户点停止时，
 * 如果没有信号，后续步骤仍会被逐个派发出去 —— 表现为「点了停止还在刷新输出」。
 * <p>
 * <b>只读语义</b>：本接口只负责「查询是否已取消」，不提供 {@code cancel()}。
 * 触发取消的权力属于 api 层（它持有会话与 WS 连接），编排层无权中止别人的回合。
 * <p>
 * <b>检查点在步骤边界</b>：编排层在每个 stage、每个 step 派发前检查一次。
 * 已在执行中的步骤由执行器自己响应中断，编排层不强杀 —— 强杀会让工具执行到一半
 * 留下半个文件，比多跑一步危害大。
 */
@FunctionalInterface
public interface CancelSignal {

    /** 永不取消，用于无中断需求的场景（如配置校验时试算） */
    CancelSignal NEVER = () -> false;

    /** 是否已请求取消 */
    boolean cancelled();
}
